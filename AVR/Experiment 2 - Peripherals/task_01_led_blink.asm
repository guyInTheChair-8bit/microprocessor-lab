.include "m8def.inc"
.CSEG
LDI R20, 0xFF
LDI R21, 0xFF
LDI R22, 0x00
OUT DDRB, R20
LDI R23, 0x14
MAIN_LOOP:
    OUT PORTB, R21
    LDI R16, 0x15
ON_LOOP:
    LDI R17, 0xFF
FIRST_LOOP:
    LDI R18, 0xFF
SECOND_LOOP:
    DEC R18
    BRNE SECOND_LOOP
    DEC R17
    BRNE FIRST_LOOP
    DEC R16
    BRNE ON_LOOP
    OUT PORTB, R22
    LDI R16, 0x15
OFF_LOOP:
    LDI R17, 0xFF
THIRD_LOOP:
    LDI R18, 0xFF
FOURTH_LOOP:
    DEC R18
    BRNE FOURTH_LOOP
    DEC R17
    BRNE THIRD_LOOP
    DEC R16
    BRNE OFF_LOOP
    DEC R23
    BRNE MAIN_LOOP
STOP:
    RJMP STOP
